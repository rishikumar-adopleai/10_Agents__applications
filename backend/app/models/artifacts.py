"""Artifacts and Evidence SQLAlchemy Models."""

from typing import Optional

from sqlalchemy import JSON, Boolean, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from backend.app.db.base import BaseModel, OrganizationScopedMixin


class ResearchBrief(BaseModel, OrganizationScopedMixin):
    """Company research brief produced by Research Agent."""

    __tablename__ = "research_briefs"

    account_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    summary: Mapped[str] = mapped_column(Text, nullable=False)
    facts: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    hypotheses: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    stakeholders: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    sources: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    version: Mapped[int] = mapped_column(Integer, default=1, nullable=False)


class BuyingSignal(BaseModel, OrganizationScopedMixin):
    """Buying signal detected by Signal Radar Agent."""

    __tablename__ = "buying_signals"

    account_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    signal_type: Mapped[str] = mapped_column(
        String(100), nullable=False
    )  # hiring_expansion, tech_stack_change, leadership_appointment, funding
    fit_reason: Mapped[str] = mapped_column(Text, nullable=False)
    fit_score: Mapped[float] = mapped_column(Float, nullable=False)
    evidence_url: Mapped[str] = mapped_column(String(500), nullable=False)
    observed_at: Mapped[str] = mapped_column(String(50), nullable=False)


class DemoArtifact(BaseModel, OrganizationScopedMixin):
    """Interactive / synthetic product demo generated by Demo Agent."""

    __tablename__ = "demo_artifacts"

    account_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    template_name: Mapped[str] = mapped_column(String(100), nullable=False)
    synthetic_payload: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    walkthrough_script: Mapped[str] = mapped_column(Text, nullable=False)
    access_token: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)
    expires_at: Mapped[str] = mapped_column(String(50), nullable=False)
    is_validated: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)


class ProposalArtifact(BaseModel, OrganizationScopedMixin):
    """Proposal drafted by Deal Desk Agent."""

    __tablename__ = "proposal_artifacts"

    account_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    opportunity_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("opportunities.id", ondelete="CASCADE"), nullable=False, index=True
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    deliverables: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    pricing_model: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    roi_assumptions: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    pilot_package: Mapped[Optional[dict]] = mapped_column(JSON, nullable=True)
    commercial_approval_status: Mapped[str] = mapped_column(
        String(50), default="draft", nullable=False
    )  # draft, approved, rejected
    approved_by_user_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)


class SecurityQuestionnaire(BaseModel, OrganizationScopedMixin):
    """Security questionnaire managed by Trust Desk Agent."""

    __tablename__ = "security_questionnaires"

    account_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    total_questions: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    answered_questions: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    qa_pairs: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    unresolved_gaps: Mapped[dict] = mapped_column(JSON, default=dict, nullable=False)
    reviewer_status: Mapped[str] = mapped_column(
        String(50), default="pending_review", nullable=False
    )  # pending_review, approved, rejected
    approved_by_user_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)


class ProofAsset(BaseModel, OrganizationScopedMixin):
    """Verified case study or metric asset from Proof Engine."""

    __tablename__ = "proof_assets"

    account_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("accounts.id", ondelete="CASCADE"), nullable=False, index=True
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    metric_before: Mapped[str] = mapped_column(String(255), nullable=False)
    metric_after: Mapped[str] = mapped_column(String(255), nullable=False)
    timeframe: Mapped[str] = mapped_column(String(100), nullable=False)
    case_study_body: Mapped[str] = mapped_column(Text, nullable=False)

    # Permission and audience scoping
    client_permission_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)
    allowed_audiences: Mapped[dict] = mapped_column(
        JSON, default=list, nullable=False
    )  # public, sales_only, partners
    is_anonymized: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    status: Mapped[str] = mapped_column(
        String(50), default="draft", nullable=False
    )  # draft, verified, published


class EvidenceRef(BaseModel, OrganizationScopedMixin):
    """Immutable evidence reference backing claims."""

    __tablename__ = "evidence_refs"

    source_url: Mapped[str] = mapped_column(String(500), nullable=False)
    source_type: Mapped[str] = mapped_column(
        String(50), nullable=False
    )  # website, doc, soc2_report, interview
    excerpt: Mapped[str] = mapped_column(Text, nullable=False)
    hash: Mapped[str] = mapped_column(String(64), nullable=False)
